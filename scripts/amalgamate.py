#!/usr/bin/env python3
"""Generate the distributable single-header version of libunicomuse."""

from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "single_include" / "unicomuse.h"
PUBLIC_HEADERS = (
    ROOT / "include" / "unicomuse" / "common.h",
    ROOT / "include" / "unicomuse" / "key.h",
    ROOT / "include" / "unicomuse" / "mouse.h",
)
IMPLEMENTATION_SOURCES = (
    ("core", ROOT / "src" / "ucomuse.c"),
    ("Windows", ROOT / "src" / "platform_windows.c"),
    ("macOS", ROOT / "src" / "platform_macos.c"),
    ("Linux", ROOT / "src" / "platform_linux.c"),
    ("FreeBSD", ROOT / "src" / "platform_freebsd.c"),
)
INTERNAL_HEADER = ROOT / "src" / "internal.h"
LOCAL_INCLUDE = re.compile(
    r'^\s*#\s*include\s+["<](?:internal\.h|common\.h|unicomuse/[^>"]+)[">]\s*$',
    re.MULTILINE,
)


def public_header_contents(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    text = LOCAL_INCLUDE.sub("", text)
    return text.strip()


def implementation_contents(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    text = LOCAL_INCLUDE.sub("", text)
    return text.strip()


def internal_declarations() -> str:
    text = INTERNAL_HEADER.read_text(encoding="utf-8")
    lines = []
    for line in text.splitlines():
        if line.startswith("#ifndef") or line.startswith("#define") or line == "#endif":
            continue
        if line.startswith("#include"):
            continue
        lines.append(line)
    return "\n".join(lines).strip()


def generate() -> str:
    license_text = (ROOT / "LICENSE").read_text(encoding="utf-8").strip()
    license_comment = "/*\n" + "\n".join(
        " * " + line if line else " *" for line in license_text.splitlines()
    ) + "\n */"
    parts = [
        license_comment,
        "/*",
        " * Generated by scripts/amalgamate.py; do not edit this file directly.",
        " * Define UCOMUSE_IMPLEMENTATION in exactly one C/C++ translation unit",
        " * before including this header to emit the implementation.",
        " */",
        "#ifndef UNICOMUSE_SINGLE_HEADER_H",
        "#define UNICOMUSE_SINGLE_HEADER_H",
        "",
        "/* POSIX declarations used by Unix platform backends. */",
        "#if defined(__linux__) || defined(__FreeBSD__)",
        "#ifndef _POSIX_C_SOURCE",
        "#define _POSIX_C_SOURCE 200809L",
        "#endif",
        "#elif defined(__APPLE__)",
        "#ifndef _POSIX_C_SOURCE",
        "#define _POSIX_C_SOURCE 199309L",
        "#endif",
        "#endif",
        "",
    ]
    parts.extend(public_header_contents(path) for path in PUBLIC_HEADERS)
    parts.extend(
        [
            "",
            "#endif /* UNICOMUSE_SINGLE_HEADER_H */",
            "",
            "#ifdef UCOMUSE_IMPLEMENTATION",
            "#ifndef UNICOMUSE_SINGLE_HEADER_IMPLEMENTED",
            "#define UNICOMUSE_SINGLE_HEADER_IMPLEMENTED",
            "",
            internal_declarations(),
            "",
            implementation_contents(IMPLEMENTATION_SOURCES[0][1]),
            "",
            "#if defined(_WIN32)",
            implementation_contents(IMPLEMENTATION_SOURCES[1][1]),
            "#elif defined(__APPLE__)",
            implementation_contents(IMPLEMENTATION_SOURCES[2][1]),
            "#elif defined(__linux__)",
            "#if defined(UCOMUSE_USE_X11) && !defined(UCOMUSE_HAVE_X11)",
            "#define UCOMUSE_HAVE_X11 1",
            "#endif",
            implementation_contents(IMPLEMENTATION_SOURCES[3][1]),
            "#elif defined(__FreeBSD__)",
            implementation_contents(IMPLEMENTATION_SOURCES[4][1]),
            "#else",
            '#error "libunicomuse single-header: unsupported operating system"',
            "#endif",
            "",
            "#endif /* UNICOMUSE_SINGLE_HEADER_IMPLEMENTED */",
            "#endif /* UCOMUSE_IMPLEMENTATION */",
            "",
        ]
    )
    return "\n".join(parts)


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generate(), encoding="utf-8", newline="\n")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
